const assert = require('node:assert/strict');
const {parseFlashcards, shuffledIndices} = require('./flashcards.js');
assert.deepEqual(parseFlashcards('A: B\nWrong line\nC: D: E'), [{question:'A',answer:'B'},{question:'C',answer:'D: E'}]);
assert.deepEqual(parseFlashcards(' : bad\nterm:'), []);
assert.deepEqual(parseFlashcards(null), []);
const order = shuffledIndices(5, () => 0.3);
assert.deepEqual(order.slice().sort(), [0,1,2,3,4]);
assert.deepEqual(shuffledIndices(3, () => 1).slice().sort(),[0,1,2]);
assert.deepEqual(shuffledIndices(3, () => -3).slice().sort(),[0,1,2]);
assert.equal(parseFlashcards('Bad\nA: useful').length,1);
assert.deepEqual(parseFlashcards('a'.repeat(100*1024+1)), []);
assert.deepEqual(shuffledIndices(1000000), []);
assert.deepEqual(shuffledIndices(-1), []);
assert.deepEqual(shuffledIndices(NaN), []);
assert.equal(shuffledIndices(200).length, 200);
console.log('THASSA flashcard input-limit and shuffle regression tests passed');
